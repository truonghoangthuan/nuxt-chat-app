import { describe, it, expect } from 'vitest'
import { mount } from '@vue/test-utils'
import { toRaw } from 'vue'
import { isValidMessageContent, MAX_MESSAGE_LENGTH } from '~/utils/chat'
import MessageComposer from '~/components/MessageComposer.vue'

describe('composer message length', () => {
  it('retains oversized text on Enter and deck Enter instead of emitting an unsendable message', async () => {
    const wrapper = mount(MessageComposer, { props: { channelSlug: 'general', conversationId: 'one' } })
    const textarea = wrapper.get('textarea')
    const draft = 'x'.repeat(4001)
    await textarea.setValue(draft)
    await textarea.trigger('keydown', { key: 'Enter' })
    await wrapper.get('[data-test="composer-deck"]').trigger('keydown', { key: 'Enter' })
    expect(wrapper.emitted('send')).toBeUndefined()
    expect((textarea.element as HTMLTextAreaElement).value).toBe(draft)
    expect(wrapper.get('button[aria-label="Send message"]').attributes('disabled')).toBeDefined()
    expect(textarea.attributes('aria-invalid')).toBe('true')
    const feedback = wrapper.get('[data-test="message-length-feedback"]')
    expect(feedback.text()).toContain('4001 / 4000')
    expect(feedback.text()).toContain('Shorten')
    expect(textarea.attributes('aria-describedby')).toBe(feedback.attributes('id'))
    await wrapper.get('button[aria-label="Send message"]').trigger('click')
    expect(wrapper.emitted('send')).toBeUndefined()
    wrapper.unmount()
  })

  it('shows feedback only near the limit and restores sending after editing', async () => {
    const wrapper = mount(MessageComposer, { props: { channelSlug: 'general' } })
    const textarea = wrapper.get('textarea')
    await textarea.setValue('x'.repeat(3599))
    expect(wrapper.find('[data-test="message-length-feedback"]').exists()).toBe(false)
    await textarea.setValue('x'.repeat(3600))
    expect(wrapper.get('[data-test="message-length-feedback"]').text()).toBe('3600 / 4000')
    expect(textarea.attributes('aria-invalid')).toBeUndefined()
    await textarea.setValue('x'.repeat(4001))
    await textarea.setValue('fixed')
    expect(textarea.attributes('aria-invalid')).toBeUndefined()
    expect(textarea.attributes('aria-describedby')).toBeUndefined()
    await wrapper.get('button[aria-label="Send message"]').trigger('click')
    expect(wrapper.emitted('send')).toEqual([['fixed']])
    expect((textarea.element as HTMLTextAreaElement).value).toBe('')
    wrapper.unmount()
  })

  it.each(['x'.repeat(4000), '😀'.repeat(2000), ` \n${'x'.repeat(4000)}\n `])('sends at the existing trimmed UTF-16 boundary (%#)', async (draft) => {
    const wrapper = mount(MessageComposer, { props: { channelSlug: 'general' } })
    const textarea = wrapper.get('textarea')
    await textarea.setValue(draft)
    expect(isValidMessageContent(draft.trim())).toBe(true)
    expect(draft.trim().length).toBe(MAX_MESSAGE_LENGTH)
    expect(wrapper.get('[data-test="message-length-feedback"]').text()).toBe('4000 / 4000')
    await textarea.trigger('keydown', { key: 'Enter', shiftKey: true })
    await textarea.trigger('keydown', { key: 'Enter', isComposing: true })
    expect(wrapper.emitted('send')).toBeUndefined()
    await textarea.trigger('keydown', { key: 'Enter' })
    expect(wrapper.emitted('send')).toEqual([[draft.trim()]])
    expect(wrapper.find('[data-test="message-length-feedback"]').exists()).toBe(false)
    wrapper.unmount()
  })

  it('keeps an oversized emoji draft and reply while switching conversations', async () => {
    const reply = { id: 'reply', content: 'Original message' } as any
    const wrapper = mount(MessageComposer, { props: { channelSlug: 'general', conversationId: 'one', replyingTo: reply } })
    const textarea = wrapper.get('textarea')
    const draft = '😀'.repeat(2000) + 'x'
    await textarea.setValue(draft)
    await textarea.trigger('keydown', { key: 'Enter' })
    expect(wrapper.emitted('send')).toBeUndefined()
    expect(wrapper.emitted('cancelReply')).toBeUndefined()
    expect(wrapper.get('[data-test="reply-banner"]').text()).toContain('Original message')
    await wrapper.setProps({ conversationId: 'two' })
    expect((textarea.element as HTMLTextAreaElement).value).toBe('')
    expect(wrapper.find('[data-test="message-length-feedback"]').exists()).toBe(false)
    await textarea.setValue('Other draft')
    await wrapper.setProps({ conversationId: 'one' })
    expect((textarea.element as HTMLTextAreaElement).value).toBe(draft)
    expect(textarea.attributes('aria-invalid')).toBe('true')
    await wrapper.setProps({ conversationId: 'two' })
    expect((textarea.element as HTMLTextAreaElement).value).toBe('Other draft')
    wrapper.unmount()
  })

  it('preserves existing image caption sends and restores the text guard when the last photo is removed', async () => {
    const wrapper = mount(MessageComposer, { props: { channelSlug: 'general' } })
    const textarea = wrapper.get('textarea')
    const caption = 'x'.repeat(4001)
    const file = new File(['image'], 'photo.png', { type: 'image/png' })
    await textarea.setValue(caption)
    await wrapper.get('[data-test="composer-deck"]').trigger('drop', { dataTransfer: { files: [file] } })
    expect(wrapper.find('[data-test="message-length-feedback"]').exists()).toBe(false)
    expect(textarea.attributes('aria-invalid')).toBeUndefined()
    expect(wrapper.get('button[aria-label="Send message"]').attributes('disabled')).toBeUndefined()
    await wrapper.get('[data-test="remove-attachment"]').trigger('click')
    expect(textarea.attributes('aria-invalid')).toBe('true')
    expect((textarea.element as HTMLTextAreaElement).value).toBe(caption)
    await wrapper.get('[data-test="composer-deck"]').trigger('drop', { dataTransfer: { files: [file] } })
    await wrapper.get('[data-test="composer-deck"]').trigger('keydown', { key: 'Enter' })
    const [files, emittedCaption] = wrapper.emitted('sendImages')![0] as [File[], string]
    expect(toRaw(files[0])).toBe(file)
    expect(emittedCaption).toBe(caption)
    expect((textarea.element as HTMLTextAreaElement).value).toBe('')
    expect(wrapper.emitted('send')).toBeUndefined()
    wrapper.unmount()
  })
})
